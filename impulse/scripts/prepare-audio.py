"""Offline asset preparation. Python + numpy only; no browser dependency.
Usage: python scripts/prepare-audio.py [path/to/RoadsterLAB_Audio.zip]
Omit the ZIP to reprocess preserved originals. Never generates new recordings.
"""
from pathlib import Path
import sys, zipfile, wave, hashlib, json
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets' / 'audio'
ORIGINAL = ASSETS / 'original'
WEB = ASSETS / 'web'
NAMES = ['background_music', 'thrust_start', 'thrust_loop', 'thrust_stop',
         'motor_low', 'motor_mid', 'motor_high', 'wreck_major', 'wreck_minor',
         'aero_noise', 'suction_start', 'suction_loop', 'suction_stop',
         'seal_leak_loop', 'surface_slide_loop', 'tire_scrub_loop', 'tire_skid_loop']
LOOPS = {'background_music', 'motor_low', 'motor_mid', 'motor_high', 'aero_noise',
         'thrust_loop', 'suction_loop', 'seal_leak_loop', 'surface_slide_loop',
         'tire_scrub_loop', 'tire_skid_loop'}
STEREO = {'background_music', 'aero_noise', 'wreck_major'}
ORIGINAL.mkdir(parents=True, exist_ok=True)
WEB.mkdir(parents=True, exist_ok=True)
if len(sys.argv) > 1:
    with zipfile.ZipFile(sys.argv[1]) as archive:
        for name in NAMES:
            # Explicit allowlist, never extract arbitrary archive paths.
            (ORIGINAL / (name + '.wav')).write_bytes(archive.read(name + '.wav'))

catalog = {}
for name in NAMES:
    path = ORIGINAL / (name + '.wav')
    with wave.open(str(path)) as w:
        sr, channels, bits, frames = w.getframerate(), w.getnchannels(), w.getsampwidth()*8, w.getnframes()
        if sr != 48000 or bits != 16:
            raise ValueError(f'{name}: expected inspected 48 kHz / 16-bit source')
        x = np.frombuffer(w.readframes(frames), dtype='<i2').reshape(-1, channels).astype(float)/32768
    source_rms = float(np.sqrt(np.mean(x*x)))
    source_jump = float(np.max(np.abs(x[-1]-x[0])))
    if name not in STEREO:
        x = np.mean(x, axis=1, keepdims=True)
    x -= np.mean(x, axis=0)  # remove DC before periodic stitching
    crossfade = .5 if name == 'background_music' else .2
    if name in LOOPS:
        n = round(sr*crossfade)
        phase = np.linspace(0, np.pi/2, n, endpoint=True)[:, None]
        seam = x[-n:]*np.cos(phase) + x[:n]*np.sin(phase)
        x = np.concatenate([x[n:-n], seam])
    else:
        # Preserve transients; short boundary fades remove hard file-edge clicks.
        attack, release = round(.003*sr), round(.035*sr)
        x[:attack] *= np.linspace(0, 1, attack)[:, None]
        x[-release:] *= np.linspace(1, 0, release)[:, None]
    # Conservative RMS matching with peak ceiling; never synthesize/restore clipped peaks.
    rms = float(np.sqrt(np.mean(x*x)))
    gain = min(4, .14/max(rms, 1e-9), .8/max(float(np.max(np.abs(x))), 1e-9))
    pcm = np.round(np.clip(x*gain, -.999, .999)*32767).astype('<i2')
    output = WEB / (name + '.wav')
    with wave.open(str(output), 'wb') as w:
        w.setnchannels(x.shape[1]); w.setsampwidth(2); w.setframerate(sr); w.writeframes(pcm.tobytes())
    catalog[name] = dict(file=name+'.wav', loop=name in LOOPS, channels=x.shape[1],
        sampleRate=sr, bits=16, duration=len(x)/sr, bytes=output.stat().st_size,
        peak=float(np.max(np.abs(pcm.astype(float)))/32768),
        rms=float(np.sqrt(np.mean((pcm.astype(float)/32768)**2))),
        seamJump=float(np.max(np.abs(pcm[0].astype(float)-pcm[-1]))/32768),
        crossfadeSeconds=crossfade if name in LOOPS else 0, processingGain=gain,
        sha256=hashlib.sha256(output.read_bytes()).hexdigest(),
        original=dict(channels=channels, sampleRate=sr, bits=bits, duration=frames/sr,
            rms=source_rms, seamJump=source_jump, sha256=hashlib.sha256(path.read_bytes()).hexdigest()))

(ASSETS/'catalog.json').write_text(json.dumps(catalog, indent=2)+'\n', encoding='utf8')
(ROOT/'src'/'audio-assets.js').write_text('// Generated by scripts/prepare-audio.py; preserve asset names.\nexport const AUDIO_ASSETS = '+json.dumps(catalog, separators=(',', ':'))+';\n', encoding='utf8')
print(f'{len(catalog)} original WAVs preserved; {sum(x["bytes"] for x in catalog.values()):,} browser bytes; 48 kHz / 16-bit PCM.')
